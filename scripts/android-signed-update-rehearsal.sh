#!/usr/bin/env bash
# No owner signing material, account access, artifact upload, uninstall or data reset.
set -euo pipefail
unset SCROBBLIX_SIGNING_STORE SCROBBLIX_SIGNING_PASSWORD_FILE
api=${1:?API required}
[[ "$api" = 26 || "$api" = 36 ]]
export JAVA_HOME="$JAVA_HOME_17_X64"
export PATH="$JAVA_HOME/bin:$ANDROID_HOME/platform-tools:$ANDROID_HOME/emulator:$ANDROID_HOME/cmdline-tools/latest/bin:$PATH"
private="$RUNNER_TEMP/disposable-signing"
mkdir -m 700 "$private"
trap 'rm -rf "$private"; if [[ -n "${emulator_pid:-}" ]]; then kill "$emulator_pid" || true; fi' EXIT
# Ephemeral test key generated by keytool; fixed test password is not an owner secret.
keytool -genkeypair -keystore "$private/test.p12" -storetype PKCS12 -alias rehearsal -storepass disposable-only -keypass disposable-only -keyalg RSA -keysize 3072 -validity 2 -dname 'CN=Disposable Update Rehearsal' >/dev/null 2>&1
android/gradlew -p android :app:assembleDebug :app:assembleDebugAndroidTest --no-daemon
cp android/app/build/outputs/apk/debug/app-debug.apk "$private/baseline.apk"
cp android/app/build/outputs/apk/androidTest/debug/app-debug-androidTest.apk "$private/test.apk"
# Rehearsal-only version override in the disposable checkout, never committed/published.
versions=$(python3 scripts/android-rehearsal-version.py android/app/build.gradle.kts)
IFS=$'\t' read -r baseline_version candidate_version <<< "$versions"
[[ "$baseline_version" =~ ^[0-9]+$ && "$candidate_version" =~ ^[0-9]+$ ]]
[[ "$candidate_version" -gt "$baseline_version" ]]
android/gradlew -p android :app:assembleRelease --no-daemon
cp android/app/build/outputs/apk/release/app-release-unsigned.apk "$private/candidate.apk"
build_tools=$(find "$ANDROID_HOME/build-tools" -mindepth 1 -maxdepth 1 -type d | sort -V | tail -1)
for name in baseline test candidate; do
  "$build_tools/apksigner" sign --ks "$private/test.p12" --ks-key-alias rehearsal --ks-pass pass:disposable-only --key-pass pass:disposable-only "$private/$name.apk"
  "$build_tools/apksigner" verify --verbose --print-certs "$private/$name.apk" > "$private/$name.signature"
done
# Strict nonempty, single-certificate equality for all three exact artifacts.
# Supports the default BuildTools37 V3.0 label and fails closed on unknown formats.
python3 qa/signer-output-contract.py "$private/signer.json" "${build_tools##*/}" "$private/baseline.signature" "$private/test.signature" "$private/candidate.signature"
for name in baseline candidate; do
  "$build_tools/aapt" dump badging "$private/$name.apk" | grep '^package:' > "$private/$name.package"
done
grep -F "name='com.frpboy.scrobblix' versionCode='$baseline_version'" "$private/baseline.package"
grep -F "name='com.frpboy.scrobblix' versionCode='$candidate_version'" "$private/candidate.package"
export ANDROID_USER_HOME="$RUNNER_TEMP/signed-update-android"
export ANDROID_EMULATOR_HOME="$ANDROID_USER_HOME"
export ANDROID_AVD_HOME="$ANDROID_USER_HOME/avd"
mkdir -p "$ANDROID_AVD_HOME"
test -e /dev/kvm
sudo chmod a+rw /dev/kvm
sdkmanager 'emulator' "system-images;android-$api;default;x86_64"
echo no | avdmanager create avd -n signed-update -k "system-images;android-$api;default;x86_64" --path "$ANDROID_AVD_HOME/signed-update.avd" --force
emulator -list-avds | grep -Fx signed-update
emulator -avd signed-update -wipe-data -no-window -no-audio -no-snapshot -gpu swiftshader_indirect -no-boot-anim > "$RUNNER_TEMP/signed-update-emulator.log" 2>&1 &
emulator_pid=$!
wait_boot() {
  timeout 180 adb wait-for-device
  for attempt in $(seq 1 120); do
    if [[ $(adb shell getprop sys.boot_completed | tr -d '\r') = 1 ]]; then return; fi
    sleep 2
  done
  return 1
}
fence() {
  adb root; adb wait-for-device
  adb shell iptables -w 30 -I OUTPUT 1 ! -o lo -j REJECT
  adb shell ip6tables -w 30 -I OUTPUT 1 ! -o lo -j REJECT
  adb shell iptables -w 30 -C OUTPUT ! -o lo -j REJECT
  adb shell ip6tables -w 30 -C OUTPUT ! -o lo -j REJECT
}
phase() {
  result=$(adb shell am instrument -w -r -e signedUpdateRehearsal disposable-isolated-only -e signedUpdatePhase "$1" -e class dev.scrobblix.app.SignedUpdateRehearsalTest com.frpboy.scrobblix.test/androidx.test.runner.AndroidJUnitRunner)
  printf '%s\n' "$result"
  printf '%s\n' "$result" | grep -F 'OK (1 test)'
  if printf '%s\n' "$result" | grep -E 'FAILURES|INSTRUMENTATION_FAILED|Process crashed'; then exit 1; fi
}
wait_boot
fence # Mandatory before either app installation or synthetic local seeding.
adb install "$private/baseline.apk"
adb install "$private/test.apk"
phase prepare
adb shell am force-stop com.frpboy.scrobblix
adb install -r "$private/candidate.apk" # No downgrade/uninstall/data-delete fallback.
phase verify
# Reboot qualification is intentionally NOT run here: guest firewall rules reset
# during reboot. It needs separately reviewed host-level network isolation first.
printf '%s\n' 'PASS disposable-certificate signed update rehearsal; reboot NOT qualified'
